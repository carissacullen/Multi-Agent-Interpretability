# ── Assembly ─────────────────────────────────────────────────────────────

def build_examples() -> list[dict]:
    """Cross every instruction pair with every domain stem.

    Returns a flat list of examples, each with:
        id, label (1=collude, 0=honest), domain, instruction_idx,
        system_prompt, user_prompt, response (the stem, to be truncated
        at extraction time).
    """
    examples = []
    for domain, stems in DOMAIN_STEMS.items():
        for stem_idx, s in enumerate(stems):
            for instr_idx, pair in enumerate(INSTRUCTION_PAIRS):
                for label_name, label in [("collude", 1), ("honest", 0)]:
                    system_prompt = pair[label_name].format(other=s["other"])
                    examples.append({
                        "id": f"{domain}__stem{stem_idx}__instr{instr_idx}__{label_name}",
                        "label": label,
                        "label_name": label_name,
                        "domain": domain,
                        "stem_idx": stem_idx,
                        "instruction_idx": instr_idx,
                        "system_prompt": system_prompt,
                        "user_prompt": s["user_prompt"],
                        "response": s["stem"],
                    })
    return examples


def main():
    parser = argparse.ArgumentParser(
        description="Generate the Collusion-Instructed-Pairs dataset"
    )
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    args = parser.parse_args()

    examples = build_examples()
    n_collude = sum(1 for e in examples if e["label"] == 1)
    n_honest = sum(1 for e in examples if e["label"] == 0)

    args.output_dir.mkdir(parents=True, exist_ok=True)
    out_path = args.output_dir / "examples.json"
    out_path.write_text(json.dumps(examples, indent=2))

    print(f"Domains: {len(DOMAIN_STEMS)}  |  Instruction pairs: {len(INSTRUCTION_PAIRS)}")
    print(f"Total examples: {len(examples)}  (collude={n_collude}, honest={n_honest})")
    print(f"Saved to {out_path}")


if __name__ == "__main__":
    main()
