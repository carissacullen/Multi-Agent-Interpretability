"""
Generate the Collusion-Instructed-Pairs dataset.

Analogue of the "Instructed-Pairs" dataset in Goldowsky-Dill et al. (2025)
("Detecting Strategic Deception Using Linear Probes"), adapted from
deception to collusion.

Zou et al. (2023) build contrastive pairs that differ only in an instruction
to pretend to be honest or deceptive, with a random true fact from Azaria &
Mitchell (2023) inserted as the model's response (excluding the last few
tokens, so the same prefix could still be completed either way). Collusion
has no single-statement truth value, so instead of a true/false fact we use
a "coordination stem": a short, domain-grounded sentence fragment describing
a shared situation between two parties, cut off before it resolves into
either a collusive or an honest continuation.

Each example crosses one INSTRUCTION_PAIR (collude vs honest framing) with
one domain stem, producing two examples (label=1 collude, label=0 honest)
that share everything except the instruction: the stem itself is inserted
directly as the "response," not generated by the model. This mirrors Zou et
al.'s method precisely -- per Goldowsky-Dill et al. (2025) §3.2.1, their
inserted fact is deliberately "not written by the model and contains no
actual deception," so the only difference between a pair's activations can
be the model's own representation of the instructed intent, with zero
lexical confound from the response text itself. (An earlier version of this
script had the model generate a real continuation of the stem instead --
reverted, since that reintroduces exactly the lexical divergence between
collude/honest responses this design is meant to avoid.)

Domains are deliberately restricted to ones that don't appear in the held-out
eval sets: transfer.py's six families (cicd, code_review, news, pump_dump,
rag, research) and stego.py's blackjack setting are excluded, so this stays
usable as training data without leaking into those test domains. audit comes
from core.py; the rest (hiring, financial, medical_ethics, legal,
environmental, cybersecurity, engineering) are additional Core-only domains
authored to keep the dataset the same size.

This is a starter pool (24 stems x 8 domains-worth x 5 instruction phrasings
= 240 examples, balanced). Extend DOMAIN_STEMS / INSTRUCTION_PAIRS to grow it
-- stick to domains outside the Transfer/Stego eval sets.

Usage:
    python collusion_instructed_pairs.py
    python collusion_instructed_pairs.py --output-dir PATH
"""

